/** اگر روز شمسی داده‌شده تعطیل رسمی باشد، عنوانش را برمی‌گرداند؛ وگرنه null */
export function getHoliday(jy: number, jm: number, jd: number): string | null {
  const solar = SOLAR.find(([m, d]) => m === jm && d === jd);
  if (solar) return solar[2];
  return LUNAR_1405[`${jy}-${jm}-${jd}`] ?? null;
}

/** آیا تاریخ میلادی، تعطیل رسمی است */
export function isHolidayDate(date: Date): boolean {
  const { jy, jm, jd } = jalaali.toJalaali(date.getFullYear(), date.getMonth() + 1, date.getDate());
  return getHoliday(jy, jm, jd) !== null;
}
